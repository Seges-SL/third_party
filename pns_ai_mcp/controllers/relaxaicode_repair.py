"""Second-pass repair of relaxaicode source that does not parse."""

import logging
import re
from .relaxaicode_replies import _log_where

_logger = logging.getLogger(__name__)


def _attempt_syntax_repair(code):
    """
    Try to fix common syntax errors in the code generated by the LLM.
    This is a fallback when the LLM generates code with minor errors.
    
    Args:
        code: Python code that may have syntax errors
    
    Returns:
        tuple: (repaired_code, was_repaired)
            - repaired_code: Repaired code (or the original if it could not be repaired)
            - was_repaired: True if repairs were made
    """
    original_code = code
    was_repaired = False
    
    # Try to fix unclosed strings at the end of lines (common error)
    # Pattern: "text not closed at end of line
    lines = code.split('\n')
    repaired_lines = []
    
    # 1. SMART repair for multi-line formatted_text (before the line-by-line pass)
    # Detect: "formatted_text": "Line 1
    # Line 2"
    # Fix: convert to "formatted_text": "Line 1\nLine 2"
    try:
        # Helper to escape newlines inside the match

        # Improved pattern: looks for the close ANCHORED to the dict structure
        # Looks for: "formatted_text": " ... " followed by , or }
        # This avoids stopping at false inner quotes
        # Group 1: Key and opening ("formatted_text": ")
        # Group 2: Content (Greedy/Non-greedy? We use non-greedy but up to the anchor)
        # Group 3: Close and separator (" , or " })
        
        # Strategy: search up to the last possible quote before a comma, closing brace OR A DOT (for chain methods)
        pattern_anchored = r"(['\"]formatted_text['\"]\s*[:=]\s*['\"])([\s\S]*?)((?<!\\)['\"]\s*(?:,|}|\]|\.))"
        
        def escape_newlines_anchored(match):
            prefix = match.group(1)
            content = match.group(2)
            suffix = match.group(3)
            if '\n' in content:
                # Escape newlines to make it a valid single-line string
                escaped = content.replace('\n', '\\n').replace('\r', '')
                return f"{prefix}{escaped}{suffix}"
            return match.group(0)
 
        code = re.sub(pattern_anchored, escape_newlines_anchored, code)

        # 1b. Same repair for footer / pie / footer_md.
        pattern_footer = (
            r"(['\"](?:footer|footer_md|pie)['\"]\s*[:=]\s*['\"])"
            r"([\s\S]*?)"
            r"((?<!\\)['\"]\s*(?:,|}|\]|\.))"
        )
        code2 = re.sub(pattern_footer, escape_newlines_anchored, code)
        if code2 != code:
            code = code2
            was_repaired = True

        # 1b2. 'footer': '<NL>'.join( → 'footer': '\n'.join(
        code2b = re.sub(
            r"(['\"])(footer|footer_md|pie)\1\s*:\s*(['\"])\s*\n\s*\3\.join\s*\(",
            r"\1\2\1: \3\\n\3.join(",
            code,
        )
        if code2b != code:
            code = code2b
            was_repaired = True

        # 1c. footer_lines = [ ... ] with broken newlines inside strings.
        try:
            def repair_footer_list(match):
                prefix, content, suffix = match.group(1), match.group(2), match.group(3)
                if '\n' not in content:
                    return match.group(0)
                escaped = content.replace('\n', '\\n').replace('\r', '')
                escaped = re.sub(r'(,\s*)\\n(\s*["\'\[\]#])', r'\1\n\2', escaped)
                escaped = re.sub(r'(\[\s*)\\n(\s*["\'\[\]#])', r'\1\n\2', escaped)
                escaped = re.sub(r'\\n(\s*\])', r'\n\1', escaped)
                return '%s%s%s' % (prefix, escaped, suffix)

            code3 = re.sub(
                r'(footer_lines\s*=\s*\[)([\s\S]*?)(\])',
                repair_footer_list,
                code,
            )
            if code3 != code:
                code = code3
                was_repaired = True
        except Exception as e:
            _logger.warning(
                '[%s] Error repairing footer_lines: %s', _log_where(), e,
            )

        # 1d. 'footer': "… not closed on the same line → '' (the weather render
        # synthesizes Comparativa + pie). Drops orphan lines of the literal.
        try:
            flines = code.split('\n')
            out = []
            skipping = False
            changed = False
            footer_open = re.compile(
                r"""^(\s*)(['\"])footer\2\s*:\s*(['\"])(.*)$"""
            )
            for ln in flines:
                if skipping:
                    st = ln.strip()
                    if st.endswith("',") or st.endswith('",') or st in ("'", '"'):
                        skipping = False
                    elif st.endswith('},') or st == '}':
                        skipping = False
                        out.append(ln)
                    continue
                m = footer_open.match(ln)
                if m:
                    indent, _k, quote, rest = m.groups()
                    # Closed on the same line: quote … quote
                    closed = re.match(
                        r'^(?:\\.|[^\\])*?' + re.escape(quote) + r'\s*,?\s*$',
                        rest,
                    )
                    if not closed:
                        out.append("%s'footer': ''," % indent)
                        skipping = True
                        changed = True
                        continue
                out.append(ln)
            if changed:
                code = '\n'.join(out)
                was_repaired = True
        except Exception as e:
            _logger.warning(
                '[%s] Error repairing footer EOL: %s', _log_where(), e,
            )

        # 2. SPECIFIC repair for formatted_lines (string lists broken by newlines)
        # Detect: formatted_lines = [ ... ] and escape inner newlines
        try:
            def repair_list_newlines(match):
                prefix = match.group(1)
                content = match.group(2)
                suffix = match.group(3)
                
                # 1. Escape ALL newlines in the content
                escaped = content.replace('\n', '\\n').replace('\r', '')
                
                # 2. Restore STRUCTURAL newlines (the ones that are part of the list syntax)
                # Pattern: restore ",\n" -> , \n
                escaped = re.sub(r'(,\s*)\\n(\s*["\'\[\]#])', r'\1\n\2', escaped)
                # Restore "[\n" -> [ \n
                escaped = re.sub(r'(\[\s*)\\n(\s*["\'\[\]#])', r'\1\n\2', escaped)
                # Restore "\n]" -> \n ] (end of list)
                escaped = re.sub(r'\\n(\s*\])', r'\n\1', escaped)

                return f"{prefix}{escaped}{suffix}"

            # Regex to capture the whole formatted_lines block
            # (formatted_lines = [) ... (])
            pattern_list = r'(formatted_lines\s*=\s*\[)([\s\S]*?)(\])'
            code = re.sub(pattern_list, repair_list_newlines, code)
            
            if code != original_code:
                was_repaired = True
        except Exception as e:
            _logger.warning(f"[{_log_where()}] Error repairing formatted_lines: {e}")

        # 3. SPECIFIC repair for broken line continuations
        # Error: unexpected character after line continuation character
        # Cause: the model puts a backslash (\) at the end of the line followed by a space or nothing.
        # Fix: remove end-of-line backslashes if they cause an error
        try:
            if '\\' in code:
                # Look for a backslash followed by a space or nothing before the newline
                # Or simply remove end-of-line backslashes if they are not needed
                # Modern Python allows parentheses for multi-line code; backslashes are risky.
                
                # Careful: do not break strings that end in a backslash (rare)
                
                def remove_broken_line_continuation(match):
                    # match.group(1) is the line content before the backslash
                    return match.group(1) + " " 
                
                # Pattern: anything that is not a backslash, followed by a backslash, optional spaces, newline
                # pattern = r'(.*)\\[ \t]*\n'
                # code = re.sub(pattern, remove_broken_line_continuation, code)
                
                # SAFER METHOD: if we detect it fails because of this, we clean ALL end-of-line backslashes
                # outside strings. (Hard with a simple regex).
                
                # Simple heuristic: replace " \n" or "\n" with " " if it looks like a broken statement?
                # Better: replace " \ " followed by a newline with nothing.
                
                if re.search(r'\\[ \t]*\n', code):
                    # Replace backslash+whitespace+newline with a single space (join lines)
                    code = re.sub(r'\\[ \t]*\n', ' ', code)
                    if code != original_code:
                        was_repaired = True

                # Special case: backslash at the END OF THE FILE (EOF)
                if code.strip().endswith('\\'):
                    code = code.strip()[:-1]
                    was_repaired = True

        except Exception as e:
            _logger.warning(f"[{_log_where()}] Error repairing line continuations: {e}")

    except Exception as e:
        _logger.warning(f"[{_log_where()}] Error trying regex repair: {e}")

            
    # 4. Repair for IMPLICIT RESULT (missing result = ... assignment)
    try:
        from ..utils.relaxaicode_recipe import (
            ensure_date_param_coercion,
            ensure_module_result_call,
            strip_self_recursive_shadow_defs,
        )
        code2, shadow_stripped = strip_self_recursive_shadow_defs(code)
        if shadow_stripped:
            code = code2
            was_repaired = True
        code2, ensured = ensure_module_result_call(code)
        if ensured:
            code = code2
            was_repaired = True
        code2, coerced = ensure_date_param_coercion(code)
        if coerced:
            code = code2
            was_repaired = True
    except Exception as e:
        _logger.warning(
            '[%s] Error in ensure_module_result_call: %s', _log_where(), e,
        )

    # 4b. Reuse distance() origin on map_pins_* when origin= was omitted
    try:
        from ..utils.relaxaicode_recipe import (
            inject_map_pins_origin_from_distance,
        )
        code2, injected = inject_map_pins_origin_from_distance(code)
        if injected:
            code = code2
            was_repaired = True
    except Exception as e:
        _logger.warning(
            '[%s] Error in inject_map_pins_origin_from_distance: %s',
            _log_where(), e,
        )

    try:
        # Check basic heuristics: 'result =' missing
        if 'result' not in code or ('=' not in code and '.search' in code):
            # [NEW] Detect use of previous_result without an assignment to result
            # If the code uses previous_result but does not assign result, we assume it wants to return previous_result
            if 'previous_result' in code and 'result =' not in code and 'result=' not in code:
                 code += "\nresult = previous_result"
                 was_repaired = True
            
            # [NEW] Detect formatted_text without an assignment to result
            elif 'formatted_text' in code and 'result =' not in code and 'result=' not in code:
                 # If 'formatted_text' is assigned to a variable
                 if re.search(r'formatted_text\s*=', code):
                     # Never grant trust to sandbox HTML; force a proper result shape.
                     code += (
                         '\nresult = {"__untrusted_html_preview__": formatted_text, '
                         '"__force_continue__": True, "__hint__": '
                         '"Do not assign bare formatted_text; return '
                         '{\'data\': [rows]} or use safe_plan_request."}'
                     )
                     was_repaired = True

            else:
                lines_clean = [l for l in code.split('\n') if l.strip() and not l.strip().startswith('#')]
                if lines_clean:
                    last_line = lines_clean[-1]
                    # If the last line looks like an expression
                    stripped_line = last_line.strip()
                    should_wrap = False
                    unwrap_print = False
                    
                    if (
                        stripped_line.startswith('env') or 
                        stripped_line.startswith('rec') or 
                        stripped_line.startswith('sorted') or 
                        stripped_line.startswith('system') or
                        stripped_line.startswith('[') or 
                        stripped_line.startswith('{')
                    ):
                        should_wrap = True
                    elif stripped_line.startswith('print(') and stripped_line.endswith(')'):
                        # Special case: print(x) -> result = x
                        should_wrap = True
                        unwrap_print = True
                    
                    if should_wrap:
                        # Find the index of the last non-empty line
                        idx_last = -1
                        current_lines = code.split('\n')
                        for i in range(len(current_lines)-1, -1, -1):
                            if current_lines[i].strip() and not current_lines[i].strip().startswith('#'):
                                idx_last = i
                                break
                        
                        if idx_last != -1:
                            indent = len(current_lines[idx_last]) - len(current_lines[idx_last].lstrip())
                            indent_str = current_lines[idx_last][:indent]
                            content = current_lines[idx_last].lstrip()
                            
                            if unwrap_print:
                                content_inner = content[6:-1] # Remove print( and )
                                current_lines[idx_last] = f"{indent_str}result = {content_inner}"
                            else:
                                current_lines[idx_last] = f"{indent_str}result = {content}"
                            
                            code = '\n'.join(current_lines)
                            was_repaired = True

    except Exception as e:
        _logger.warning(f"[{_log_where()}] Error repairing implicit result: {e}")

    # 5. Remove a stray `result` line at the end (REPL quirk in context snippets)
    try:
        lines = code.rstrip().split('\n')
        while lines and lines[-1].strip() == 'result':
            lines.pop()
            was_repaired = True
        if was_repaired:
            code = '\n'.join(lines)
            if code and not code.endswith('\n'):
                code += '\n'
    except Exception as e:
        _logger.warning(f"[{_log_where()}] Error removing trailing bare result: {e}")

    # 6. result.append/extend with no prior result = [] (very common trial_balance pattern)
    try:
        if re.search(r'\bresult\.(append|extend)\s*\(', code):
            assigns_before_append = False
            out_lines = []
            for line in code.split('\n'):
                stripped = line.strip()
                if stripped and not stripped.startswith('#'):
                    if re.match(r'result\s*(?:\+)?=', stripped):
                        assigns_before_append = True
                    if (
                        re.search(r'\bresult\.(append|extend)\s*\(', line)
                        and not assigns_before_append
                    ):
                        indent = len(line) - len(line.lstrip())
                        indent_str = line[:indent]
                        out_lines.append(f"{indent_str}result = []")
                        assigns_before_append = True
                        was_repaired = True
                out_lines.append(line)
            if was_repaired:
                code = '\n'.join(out_lines)
    except Exception as e:
        _logger.warning(f"[{_log_where()}] Error repairing result.append without init: {e}")

    if was_repaired:
        lines = code.split('\n')
    
    for i, line in enumerate(lines):
        repaired_line = line
        
        # Detect unclosed strings: a line ending with an unclosed single or double quote
        # But only if it is not a comment and has an opening quote
        if not line.strip().startswith('#'):
            # Count single and double quotes
            single_quotes = line.count("'") - line.count("\\'")
            double_quotes = line.count('"') - line.count('\\"')
            
            # If there is an odd number of quotes, the string is not closed
            # Try to close it if the line ends with text (not with an operator, etc.)
            if (single_quotes % 2 == 1 or double_quotes % 2 == 1) and line.strip():
                # Check whether the line looks like part of an assignment to result
                if 'result' in line and 'formatted_text' in line:
                    # If it ends with an unclosed quote, try to close it
                    if line.rstrip().endswith('"') and double_quotes % 2 == 1:
                        # It already has a quote at the end, but it is malformed
                        # It may be missing a close before a line break
                        pass
                    elif not line.rstrip().endswith(('"', "'")):
                        # The line does not end with a quote, add it
                        if double_quotes % 2 == 1:
                            repaired_line = line.rstrip() + '"'
                            was_repaired = True
                        elif single_quotes % 2 == 1:
                            repaired_line = line.rstrip() + "'"
                            was_repaired = True
        
        repaired_lines.append(repaired_line)
    
    if was_repaired:
        repaired_code = '\n'.join(repaired_lines)
        # Check that the repaired code is syntactically valid
        try:
            import ast
            ast.parse(repaired_code, '<relaxaicode>', 'exec')
            return repaired_code, True
        except SyntaxError:
            _logger.warning(f"[{_log_where()}] Automatic repair failed - code still invalid")
            return original_code, False
    
    return original_code, False
